"""B1: complete verbatim prompts, generated from the frozen serializer and templates (so the listing in the paper
cannot drift from the code). The example is the graph of Figure 1a (elk, jar, fig, oak, owl, hen; oak and hen red)
with query vertex elk and question D1a. Writes prompt_box.tex (plain text, no float): every format
under template T1, D1a under T2 and T3 (AL), the E8 variants as differences from the T1 AL prompt, and the
string after the Qwen2.5 chat template. Line breaks are shown as a return arrow.
Usage: python prompt_box.py --out prompt_box.tex
"""
import re
import argparse
import random
from pathlib import Path

import networkx as nx

from instances import SER_OFFSET
from prompts import render
from serialize import serialize
from tasks import BY_ID

NAMES = ["elk", "jar", "fig", "oak", "owl", "hen"]
COLORS = ["blue", "blue", "blue", "red", "blue", "red"]
EDGES = [(0, 1), (0, 2), (1, 3), (2, 4), (4, 5), (3, 5)]
SEED = 7
FORMATS = [("EL", "EL"), ("AL", "AL"), ("NC", "NC"), ("ECL", "ECL"), ("ELB", "ELB"), ("EL2", "EL-2"), ("ELfar", "EL-far"),
           ("NCH", "NC-H"), ("NCnw", "NC-nw"), ("Incident", "Incident"), ("Friendship", "Friendship"),
           ("GraphML", "GraphML")]
# the default chat template of Qwen2.5 (system message included by the tokenizer when none is given); the run
# writes the rendered string of three prompts per model to results/rendered_prompts.txt
QWEN = ("<|im_start|>system\nYou are Qwen, created by Alibaba Cloud. You are a helpful assistant.<|im_end|>\n"
        "<|im_start|>user\n{p}<|im_end|>\n<|im_start|>assistant\n")


def graph(colors=COLORS):
    G = nx.Graph()
    G.add_nodes_from(range(6))
    G.add_edges_from(EDGES)
    for u, c in enumerate(colors):
        G.nodes[u]["color"] = c
    return G


def prompt(kind, tpl="T1", names=None, question_first=False, sort_edges=False, colors=COLORS):
    names = names or dict(enumerate(NAMES))
    G = graph(colors)
    text = serialize(G, names, kind, seed=SEED + SER_OFFSET[kind], sort_edges=sort_edges)
    q = BY_ID["D1a"].question.format(v=names[0])
    cols = sorted(set(colors) | {"red", "blue"}, key=["red", "blue", "green"].index)
    return render(tpl, text, q, colors=cols, question_first=question_first)


def tex(s):
    rep = {"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}", "_": r"\_", "#": r"\#", "%": r"\%", "&": r"\&",
           "$": r"\$", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "-": "-{}", "<": r"\textless{}",
           ">": r"\textgreater{}", '"': r"\textquotedbl{}", "'": r"\textquotesingle{}"}
    out = "".join(rep.get(ch, ch) for ch in s)
    out = out.replace(" ", r"\ ")                        # keep the leading space of every serialization line
    return r"\\".join(ln + r"$\hookleftarrow$" for ln in out.split("\n")[:-1]) + (r"\\" if "\n" in s else "") + out.split("\n")[-1]


def block(title, s):
    title = re.sub(r"(?<![\\$A-Za-z{])(ECL|ELB|EL|AL|NC)(?![A-Za-z}])", lambda m_: "$\\" + m_.group(1) + "$", title)   # format names as in the text
    return (f"\\paragraph{{{title}.}}\\leavevmode\\\\\n{{\\ttfamily\\scriptsize\\raggedright\\noindent "
            f"{tex(s)}\\par}}\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="prompt_box.tex")
    a = ap.parse_args()
    parts = ["% generated by m0/prompt_box.py from the frozen serializer and templates; do not edit\n"]
    for k, lab in FORMATS:
        parts.append(block(f"{lab}, template T1", prompt(k)))
    for t in ("T2", "T3"):
        parts.append(block(f"AL, template {t}", prompt("AL", t)))
    base = prompt("AL").split("\n")
    ints = prompt("AL", names={u: str(u) for u in range(6)}).split("\n")
    qf = prompt("AL", question_first=True)
    parts.append(block("E8, integer identifiers (AL, T1; changed lines)",
                       "\n".join(b for a_, b in zip(base, ints) if a_ != b) + "\n"))
    parts.append(block("E8, question first (AL, T1)", qf))
    parts.append(block("E8, edges sorted by source vertex (EL, T1; the seven edge lines, in sorted order)",
                       "\n".join(prompt("EL", sort_edges=True).split("\n")[3:3 + 7]) + "\n"))
    c3 = list(COLORS)
    c3[4] = "green"
    parts.append(block("E8, three colors (AL, T1; owl green instead of blue; changed lines only)",
                       "\n".join(b for a_, b in zip(base, prompt("AL", colors=c3).split("\n")) if a_ != b) + "\n"))
    parts.append(block("Qwen2.5 chat input (AL, T1)", QWEN.format(p=prompt("AL"))))
    Path(a.out).write_text("".join(parts))
    print("wrote", a.out)


if __name__ == "__main__":
    main()
